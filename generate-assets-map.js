/* eslint-disable no-undef */
const fs = require('fs');
const path = require('path');

const imagesDir = path.join(__dirname, 'assets/images/questions');
const outputFile = path.join(__dirname, 'features/pyq/question-images.ts');

try {
  if (!fs.existsSync(imagesDir)) {
    fs.mkdirSync(imagesDir, { recursive: true });
  }

  const files = fs.readdirSync(imagesDir);
  const imageFiles = files.filter((f) => /\.(jpg|jpeg|png|gif|webp)$/i.test(f));

  let content = `// This file is automatically generated. Do not edit manually.\n`;
  content += `export const questionImages: Record<string, any> = {\n`;

  imageFiles.forEach((file) => {
    content += `  '${file}': require('@/assets/images/questions/${file}'),\n`;
  });

  content += `};\n`;

  fs.writeFileSync(outputFile, content, 'utf8');
  console.log(`Generated mapping for ${imageFiles.length} images.`);
} catch (err) {
  console.error('Error generating asset map:', err);
  process.exit(1);
}
